// Script para verificar si Poppler está instalado
import { exec } from 'child_process';
import { promisify } from 'util';

const execAsync = promisify(exec);

console.log('🔍 Verificando instalación de Poppler...\n');

async function checkPoppler() {
  try {
    // Intentar con pdftoppm (comando principal)
    console.log('1. Probando comando "pdftoppm -v"...');
    const { stdout: pdftoppmOutput } = await execAsync('pdftoppm -v');
    console.log('✅ Poppler está instalado (pdftoppm)');
    console.log('📋 Información:', pdftoppmOutput.split('\n')[0]);
    return true;
  } catch (pdftoppmError) {
    console.log('❌ Comando "pdftoppm" no encontrado');
    
    try {
      // Intentar con pdfinfo
      console.log('\n2. Probando comando "pdfinfo -v"...');
      const { stdout: pdfinfoOutput } = await execAsync('pdfinfo -v');
      console.log('✅ Poppler está instalado (pdfinfo)');
      console.log('📋 Información:', pdfinfoOutput.split('\n')[0]);
      return true;
    } catch (pdfinfoError) {
      console.log('❌ Comando "pdfinfo" no encontrado');
      return false;
    }
  }
}

async function checkCommonPaths() {
  console.log('\n3. Verificando rutas comunes de instalación...');
  
  const commonPaths = [
    'C:\\poppler\\bin\\pdftoppm.exe',
    'C:\\poppler\\bin\\pdfinfo.exe',
    'C:\\Program Files\\poppler\\bin\\pdftoppm.exe',
    'C:\\Program Files (x86)\\poppler\\bin\\pdftoppm.exe',
    'C:\\tools\\poppler\\bin\\pdftoppm.exe'
  ];
  
  const fs = await import('fs');
  
  for (const path of commonPaths) {
    try {
      if (fs.existsSync(path)) {
        console.log(`✅ Encontrado en: ${path}`);
        return true;
      }
    } catch (error) {
      // Continuar con la siguiente ruta
    }
  }
  
  console.log('❌ No se encontró Poppler en las rutas comunes');
  return false;
}

